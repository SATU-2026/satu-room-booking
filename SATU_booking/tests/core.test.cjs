const assert=require('node:assert/strict');
const C=require('../core.js');
const now=new Date('2026-10-26T05:00:00Z');
const make=(s,e,status='pending',room_id='rs-a205')=>({room_id,starts_at:C.stamp('2026-11-01',s),ends_at:C.stamp('2026-11-01',e),status});
assert.equal(C.overlap(make('09:00','11:00'),make('11:00','12:00')),false,'Adjacent bookings must be allowed');
for(const pair of [['08:00','10:00'],['10:00','12:00'],['09:00','11:00'],['08:00','12:00'],['09:30','10:30']])assert(C.overlap(make('09:00','11:00'),make(...pair)),'All overlapping shapes must be rejected');
for(const status of ['cancelled','rejected'])assert.equal(C.overlap(make('09:00','11:00'),make('09:00','11:00',status)),false);
assert.equal(C.overlap(make('09:00','11:00'),make('09:00','11:00','blocked')),true);
assert.equal(C.overlap(make('09:00','11:00'),make('09:00','11:00','pending','tp-01')),false);
assert.equal(C.canScope([{role:'staff',campus_id:'rs'}],'tp'),false);
assert.equal(C.canScope([{role:'head',campus_id:'rs'},{role:'head',campus_id:'tp'}],'tp',['head']),true);
assert.equal(C.canScope([{role:'staff',campus_id:'rs'}],'rs',['head']),false);
assert(C.canScope([{role:'admin',campus_id:null}],'tp',['admin']));
const b={...make('09:00','11:00'),phone:'private',fullname:'private',token:'private'};
assert(!('phone' in C.publicRecord(b)));assert(!('fullname' in C.publicRecord(b)));assert(!('token' in C.publicRecord(b)));
assert.equal(C.canCancel(b,new Date('2026-11-01T01:00:00Z')),true,'Exactly 1 hour before start');
assert.equal(C.canCancel(b,new Date('2026-11-01T01:00:01Z')),false);
const valid={...make('09:00','11:00'),fullname:'test',student_id:'demo',phone:'0800000000',faculty:'test',group_name:'test',detail:'test',participants:20};
assert(C.validate(valid,now));
assert.throws(()=>C.validate({...valid,ends_at:valid.starts_at},now));
assert.throws(()=>C.validate({...valid,starts_at:C.stamp('2026-10-30','09:00'),ends_at:C.stamp('2026-10-30','11:00')},now));
assert.throws(()=>C.validate({...valid,ends_at:C.stamp('2026-11-02','11:00')},now));
assert.throws(()=>C.validate({...valid,participants:0},now));
assert.throws(()=>C.validate({...valid,phone:'123'},now));
assert.equal(C.bangkokDate(new Date('2026-10-26T18:00:00Z')),'2026-10-27');
assert.equal(C.phone('080-000-0000'),'0800000000');
console.log('PASS: overlap, adjacency, cancellation, campus roles, privacy projection, dates and validation');
